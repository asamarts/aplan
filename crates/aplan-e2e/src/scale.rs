//! A plan of a given size and cut width, written deterministically (`A1-229`).
//!
//! Every number in `A1-226`, `A1-227` and `A1-228` came from a script written to
//! answer one question and then deleted, which is how the quadratic in
//! `A1-227` survived long enough to be measured at 25 seconds. This is the
//! generator those scripts kept re-inventing, committed so the next measurement
//! starts from the same plan.
//!
//! **The shape matters more than the size.** A single "10,000 tasks" fixture
//! would have missed the quadratic entirely: it was in a cut's *width*, so
//! finding it needed the task count held constant while the number of cuts they
//! are spread across varied. [`Shape`] is built around that.
//!
//! Deterministic by construction: ids are formatted from indices, nothing reads
//! the clock or a random source, and two calls with the same [`Shape`] write
//! byte-identical trees. A benchmark whose fixture moves is measuring the
//! fixture.

use std::io;
use std::path::Path;

/// The shape of a generated plan: how many tasks, and how few cuts they are
/// gathered into.
#[derive(Debug, Clone, Copy)]
pub struct Shape {
    /// Member tasks. The plan also holds one milestone per cut, so the file
    /// count is `tasks + cuts`.
    pub tasks: usize,
    /// How many cuts the tasks are spread across. `tasks / cuts` is a cut's
    /// width, and the width is what the interesting costs scale with.
    pub cuts: usize,
    /// Give every task after the first in its cut a dependency on the one
    /// before it.
    ///
    /// Off, the only edges in the plan are cut membership, and `graph` excludes
    /// those by default and refuses with "no task in view has a dependency on
    /// another" -- so a measurement of `graph` across two plans where only one
    /// has membership compares a refusal against a render. `A1-228` published
    /// such a number. On, both reach the same code path.
    pub deps: bool,
}

impl Shape {
    /// A cut's membership count, which is the term the costs scale with.
    #[must_use]
    pub fn width(&self) -> usize {
        self.tasks / self.cuts
    }
}

/// Write a plan of `shape` under `root`, creating `root/aplan/tasks` and a
/// minimal `.aplan.yml`.
///
/// # Errors
/// Returns any I/O error from creating the directories or writing a file.
pub fn write_plan(root: &Path, shape: &Shape) -> io::Result<()> {
    let tasks_dir = root.join("aplan/tasks");
    std::fs::create_dir_all(&tasks_dir)?;
    std::fs::write(root.join(".aplan.yml"), "root: aplan\n")?;

    let width = shape.width();
    for c in 0..shape.cuts {
        let members: Vec<String> = (0..width).map(|i| task_id(c, i)).collect();
        for (i, id) in members.iter().enumerate() {
            let blocked = if shape.deps && i > 0 {
                format!("blocked_by: [{}]\n", members[i - 1])
            } else {
                String::new()
            };
            std::fs::write(
                tasks_dir.join(format!("{id}.md")),
                format!(
                    "---\nid: {id}\ntitle: a task\nphase: 0\nstatus: todo\nowner: t\n\
                     effort_days: 1\n{blocked}---\n\n## Why\n\nGenerated by `aplan-e2e::scale`.\n"
                ),
            )?;
        }
        let cut = cut_id(c);
        std::fs::write(
            tasks_dir.join(format!("{cut}.md")),
            format!(
                "---\nid: {cut}\ntitle: a cut\nphase: 0\nstatus: todo\nowner: t\n\
                 tags: [milestone]\nblocked_by: [{}]\n---\n\n## Why\n\nGenerated by `aplan-e2e::scale`.\n",
                members.join(", ")
            ),
        )?;
    }
    Ok(())
}

/// The id of member `i` of cut `c`. Zero-padded so lexical and numeric order
/// agree, which keeps a directory listing stable.
#[must_use]
pub fn task_id(cut: usize, index: usize) -> String {
    format!("T-{cut:05}-{index:05}")
}

/// The id of cut `c`.
#[must_use]
pub fn cut_id(cut: usize) -> String {
    format!("M-{cut:05}")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tree(root: &Path) -> Vec<(String, String)> {
        let mut out: Vec<(String, String)> = std::fs::read_dir(root.join("aplan/tasks"))
            .expect("tasks dir")
            .flatten()
            .map(|e| {
                (
                    e.file_name().to_string_lossy().into_owned(),
                    std::fs::read_to_string(e.path()).expect("read"),
                )
            })
            .collect();
        out.sort();
        out
    }

    /// The generator writes the shape it was asked for, which everything that
    /// times it depends on and none of those timings can check.
    #[test]
    fn a_plan_holds_the_tasks_and_the_cut_width_it_was_asked_for() {
        let dir = tempfile::Builder::new()
            .tempdir_in(aplan_core::fixture::fixture_root())
            .expect("tempdir");
        let shape = Shape {
            tasks: 12,
            cuts: 3,
            deps: false,
        };
        write_plan(dir.path(), &shape).expect("write");
        assert_eq!(shape.width(), 4);
        assert_eq!(
            tree(dir.path()).len(),
            12 + 3,
            "one file per task and per cut"
        );
        let cut = std::fs::read_to_string(dir.path().join(format!("aplan/tasks/{}.md", cut_id(0))))
            .expect("cut");
        for i in 0..4 {
            assert!(
                cut.contains(&task_id(0, i)),
                "the cut does not list {}",
                task_id(0, i)
            );
        }
    }

    /// **Two runs of one shape are byte-identical**, which is what makes a
    /// measurement across two commits a measurement of the code (`A1-229`).
    #[test]
    fn the_same_shape_writes_the_same_bytes_twice() {
        let shape = Shape {
            tasks: 12,
            cuts: 3,
            deps: true,
        };
        let a = tempfile::Builder::new()
            .tempdir_in(aplan_core::fixture::fixture_root())
            .expect("tempdir");
        let b = tempfile::Builder::new()
            .tempdir_in(aplan_core::fixture::fixture_root())
            .expect("tempdir");
        write_plan(a.path(), &shape).expect("write");
        write_plan(b.path(), &shape).expect("write");
        assert_eq!(tree(a.path()), tree(b.path()));
    }

    /// `deps` is what stops a comparison timing a refusal against a render, so
    /// it has to actually put edges in (`A1-228`).
    #[test]
    fn deps_adds_a_dependency_to_every_task_but_the_first_in_its_cut() {
        let dir = tempfile::Builder::new()
            .tempdir_in(aplan_core::fixture::fixture_root())
            .expect("tempdir");
        write_plan(
            dir.path(),
            &Shape {
                tasks: 6,
                cuts: 2,
                deps: true,
            },
        )
        .expect("write");
        let first =
            std::fs::read_to_string(dir.path().join(format!("aplan/tasks/{}.md", task_id(0, 0))))
                .expect("read");
        let second =
            std::fs::read_to_string(dir.path().join(format!("aplan/tasks/{}.md", task_id(0, 1))))
                .expect("read");
        assert!(
            !first.contains("blocked_by"),
            "the first task waits on nothing"
        );
        assert!(
            second.contains(&format!("blocked_by: [{}]", task_id(0, 0))),
            "the second task does not wait on the first"
        );
    }
}
