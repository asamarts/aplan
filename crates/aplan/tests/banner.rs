//! The generated roadmap's regenerate line is a command that works (`A1-059`).
//!
//! It used to be this repository's own self-hosting invocation, `cargo run -q -p
//! aplan -- roadmap --format markdown > ROADMAP.status.md`, emitted into every
//! consumer's committed file. In the third pilot there is no `-p aplan` package
//! to run and the file is not at that path, so the banner was wrong twice
//! (pre-public adoption evidence, via `A1-050`).
//!
//! That is worse than a cosmetic slip. The banner convention exists so a
//! generated artifact names the command that regenerates it, and the file is
//! diffed against its generator, so a consumer cannot correct it by hand: a
//! wrong regenerate line regenerates identically wrong.

use std::path::Path;

mod common;
use common::aplan;

/// One cut with one member, which is enough to render a roadmap.
fn repo() -> tempfile::TempDir {
    let dir = tempfile::Builder::new()
        .tempdir_in(aplan_core::fixture::fixture_root())
        .expect("tempdir");
    let root = dir.path();
    std::fs::create_dir_all(root.join("aplan/tasks")).expect("plan dir");
    std::fs::write(
        root.join("aplan/tasks/M-v0.1.md"),
        "---\nid: M-v0.1\ntitle: The first cut of this fixture\nphase: 1\n\
         status: todo\nowner: kaminsod\ntags: [milestone]\nblocked_by: [A-1]\n---\n\n\
         ## Exit criteria\n\nSomething.\n",
    )
    .expect("milestone");
    std::fs::write(
        root.join("aplan/tasks/A-1.md"),
        "---\nid: A-1\ntitle: A task that belongs to the first cut\nphase: 1\n\
         status: todo\nowner: kaminsod\neffort_days: 1\npaths:\n- src/**\n---\n\n\
         ## Why\n\nSomething.\n",
    )
    .expect("task");
    dir
}

/// The banner's second line, without its comment wrapper and backticks.
///
/// The shape is asserted rather than trimmed off hopefully. `trim_start_matches`
/// on a line that does not carry the prefix returns the line unchanged, so a
/// caller asserting "the command names no path" would have passed against a
/// banner that had been deleted, which is the wrong-reason pass this file is
/// otherwise about.
fn regenerate_line(markdown: &str) -> String {
    const PREFIX: &str = "<!-- regenerate: `";
    const SUFFIX: &str = "` -->";
    // Line 1 is the "generated by" line, which stays: the finding was about the
    // second line only, and nothing else pinned the first one surviving.
    let mut lines = markdown.lines();
    assert_eq!(
        lines.next(),
        Some("<!-- generated by `aplan roadmap --format markdown`; do not edit. -->"),
        "the first banner line changed:\n{markdown}"
    );
    let line = lines.next().expect("the banner is two lines");
    let inner = line
        .strip_prefix(PREFIX)
        .and_then(|l| l.strip_suffix(SUFFIX))
        .unwrap_or_else(|| panic!("line 2 is not a regenerate banner: {line}"));
    assert!(
        !inner.is_empty(),
        "the banner names no command at all: {line}"
    );
    inner.to_string()
}

/// The acceptance criterion, literally.
#[test]
fn the_banner_names_no_package_of_ours() {
    let dir = repo();
    let (out, code) = aplan(
        dir.path(),
        &["roadmap", "--root", "aplan", "--format", "markdown"],
    );
    assert_eq!(code, 0, "{out}");
    assert!(!out.contains("-p aplan"), "{out}");
    assert!(!out.contains("cargo run"), "{out}");
    // Through the parser, so a deleted banner fails here rather than passing for
    // want of a string to find `-p aplan` in.
    assert_eq!(
        regenerate_line(&out),
        "aplan roadmap --format markdown",
        "{out}"
    );
}

/// And it names no output path, rather than the wrong one: only the consumer
/// knows where their copy of the file lives, so the redirection is theirs.
#[test]
fn the_banner_names_no_output_path() {
    let dir = repo();
    let (out, _) = aplan(
        dir.path(),
        &["roadmap", "--root", "aplan", "--format", "markdown"],
    );
    let cmd = regenerate_line(&out);
    assert!(!cmd.contains('>'), "the banner redirects somewhere: {cmd}");
    assert!(!cmd.contains(".md"), "the banner names a path: {cmd}");
}

/// The strongest form of the criterion: take the command the banner names, run
/// it, and require that it works. An assertion about the text would pass on a
/// banner naming a subcommand that does not exist.
#[test]
fn the_command_the_banner_names_actually_runs_and_reproduces_the_file() {
    let dir = repo();
    let (first, _) = aplan(
        dir.path(),
        &["roadmap", "--root", "aplan", "--format", "markdown"],
    );
    let cmd = regenerate_line(&first);

    let mut words = cmd.split_whitespace();
    assert_eq!(words.next(), Some("aplan"), "the banner names another tool");
    let rest: Vec<&str> = words.collect();
    // `--root` is this fixture's, not the banner's business: a consumer runs the
    // command from their own repository root, where the default applies.
    let mut args = vec!["--root", "aplan"];
    args.extend(rest);
    let (second, code) = aplan(dir.path(), &args);

    assert_eq!(code, 0, "the banner's own command failed:\n{second}");
    assert_eq!(
        first, second,
        "the command the banner names does not reproduce the file"
    );
}

/// A repository whose generator is a wrapper says so, which is what makes the
/// line true where a bare command would be merely runnable. This one is
/// dogfooded: it is how this repository's own `ROADMAP.status.md` names
/// `cargo xtask gen-roadmap`.
#[test]
fn a_wrapper_command_is_named_verbatim() {
    let dir = repo();
    let (out, code) = aplan(
        dir.path(),
        &[
            "roadmap",
            "--root",
            "aplan",
            "--format",
            "markdown",
            "--regenerate-with",
            "make roadmap",
        ],
    );
    assert_eq!(code, 0, "{out}");
    assert_eq!(regenerate_line(&out), "make roadmap", "{out}");
}

/// This repository's committed file is the worked example, so the claim is
/// checked against the artifact rather than only against the renderer.
///
/// Proves the named behaviour `generated.names_the_build_that_wrote_it`.
///
/// It asserts the artifact, not the generator: making `xtask` pass `None` would
/// leave this passing until the file were regenerated. That gap is covered, and
/// measured rather than assumed: `cargo xtask gen-roadmap --check` exits 1 under
/// exactly that mutation, which is what a drift gate is for.
/// A generated artifact says which build wrote it (`A1-325`).
///
/// The pilot's failure was a thirty-line diff with nothing explaining it: the
/// file had been regenerated by a different build, and the check that compares
/// it is green by construction wherever both sides are the same build -- which
/// is always, on the machine where it is run (pre-public adoption evidence item
/// 13). One line makes the difference visible in the diff itself.
#[test]
fn the_committed_roadmap_says_which_build_wrote_it() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let text = std::fs::read_to_string(root.join("ROADMAP.status.md")).expect("read");
    let line = text
        .lines()
        .find(|l| l.contains("written by aplan"))
        .expect("the committed artifact names no build");
    assert!(
        line.contains(env!("CARGO_PKG_VERSION")),
        "the banner names a version this build does not have: {line}"
    );
    // The surface digest, not only the version: every build from `main` carries
    // the same version, so on its own it cannot tell two development builds
    // apart, which is the case `A1-256` exists for.
    assert!(
        line.contains("surface "),
        "the banner carries no surface digest, so two dev builds look identical: {line}"
    );

    // And the same line is in the block every adopter compares, placed *inside*
    // the markers: `A1-294` made the begin marker a literal an adopter copies by
    // hand, and `contract.begin_marker_matched_by_prefix` pins how it is found.
    let agents = std::fs::read_to_string(root.join("AGENTS.md")).expect("read");
    let begin = agents
        .lines()
        .position(|l| l.contains("aplan:begin"))
        .expect("the block is fenced");
    let written = agents
        .lines()
        .position(|l| l.contains("written by aplan"))
        .expect("the generated block names no build");
    assert!(
        written > begin,
        "the build identity must sit inside the block, never in the marker"
    );
    assert!(
        !agents
            .lines()
            .nth(begin)
            .expect("begin")
            .contains("written by"),
        "the marker itself was changed, which every adopter would have to copy again"
    );
}

#[test]
fn this_repositorys_own_committed_banner_is_truthful() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join("ROADMAP.status.md");
    let text = std::fs::read_to_string(&path).expect("the committed roadmap");
    assert_eq!(
        regenerate_line(&text),
        "cargo xtask gen-roadmap",
        "the committed banner does not name this repository's generator"
    );
    assert!(!text.contains("-p aplan"), "the old invocation is back");
}

