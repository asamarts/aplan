/// `-->` closes the comment early and spills the rest into the document.
#[test]
fn a_command_that_would_close_the_comment_is_refused() {
    let dir = repo();
    let (out, code) = aplan(
        dir.path(),
        &[
            "roadmap",
            "--root",
            "aplan",
            "--format",
            "markdown",
            "--regenerate-with",
            "x --> y",
        ],
    );
    assert_eq!(code, 2, "a bad flag value is a usage error:\n{out}");
    assert!(out.contains("`-->`"), "{out}");
    assert!(!out.contains("# Roadmap"), "it rendered anyway:\n{out}");
}

/// A newline moves the banner off the line every consumer reads it on.
#[test]
fn a_multi_line_command_is_refused() {
    let dir = repo();
    let (out, code) = aplan(
        dir.path(),
        &[
            "roadmap",
            "--root",
            "aplan",
            "--format",
            "markdown",
            "--regenerate-with",
            "a\nb",
        ],
    );
    assert_eq!(code, 2, "{out}");
    assert!(out.contains("single-line"), "{out}");
}

/// An empty value would name no command at all, which is worse than the default
/// it replaced.
#[test]
fn an_empty_command_is_refused() {
    let dir = repo();
    let (out, code) = aplan(
        dir.path(),
        &[
            "roadmap",
            "--root",
            "aplan",
            "--format",
            "markdown",
            "--regenerate-with",
            "   ",
        ],
    );
    assert_eq!(code, 2, "{out}");
    assert!(out.contains("is empty"), "{out}");
}

/// On a format with no banner the flag would be accepted and ignored, which
/// reads exactly like a flag that worked.
#[test]
fn the_flag_is_refused_on_a_format_that_has_no_banner() {
    let dir = repo();
    for format in ["human", "json"] {
        let (out, code) = aplan(
            dir.path(),
            &[
                "roadmap",
                "--root",
                "aplan",
                "--format",
                format,
                "--regenerate-with",
                "make roadmap",
            ],
        );
        assert_eq!(code, 2, "`--format {format}` accepted it:\n{out}");
        assert!(out.contains("only `--format markdown`"), "{out}");
    }
}

/// A backtick delimits the command in the banner, so a value carrying one makes
/// the field unparseable: nothing reading the line can tell where the command
/// ends, which is the `-->` defect one delimiter in.
#[test]
fn a_command_containing_a_backtick_is_refused() {
    let dir = repo();
    let (out, code) = aplan(
        dir.path(),
        &[
            "roadmap",
            "--root",
            "aplan",
            "--format",
            "markdown",
            "--regenerate-with",
            "make `x`",
        ],
    );
    assert_eq!(code, 2, "{out}");
    assert!(out.contains("backtick"), "{out}");
    assert!(!out.contains("# Roadmap"), "it rendered anyway:\n{out}");
}

/// `char::is_control` does not cover U+2028 and U+2029. Rust's own `lines()`
/// ignores them, so this passes every check written in Rust and splits the banner
/// in a consumer's drift gate written in something else.
#[test]
fn a_command_containing_a_unicode_line_separator_is_refused() {
    let dir = repo();
    for sep in ["a\u{2028}b", "a\u{2029}b"] {
        let (out, code) = aplan(
            dir.path(),
            &[
                "roadmap",
                "--root",
                "aplan",
                "--format",
                "markdown",
                "--regenerate-with",
                sep,
            ],
        );
        assert_eq!(code, 2, "{sep:?} was accepted:\n{out}");
        assert!(out.contains("line separator"), "{out}");
    }
}

/// The value lands in a byte-exact generated file, so padding would make two
/// repositories naming the same command produce two different files. The blank
/// check already reads the trimmed form, so keeping the padding was the
/// inconsistency.
#[test]
fn a_padded_command_is_trimmed_rather_than_written_as_given() {
    let dir = repo();
    let (padded, code) = aplan(
        dir.path(),
        &[
            "roadmap",
            "--root",
            "aplan",
            "--format",
            "markdown",
            "--regenerate-with",
            "   make roadmap   ",
        ],
    );
    assert_eq!(code, 0, "{padded}");
    assert_eq!(regenerate_line(&padded), "make roadmap", "{padded}");

    // Byte-identical to the unpadded form, which is the property that matters:
    // the drift gate compares whole files.
    let (plain, _) = aplan(
        dir.path(),
        &[
            "roadmap",
            "--root",
            "aplan",
            "--format",
            "markdown",
            "--regenerate-with",
            "make roadmap",
        ],
    );
    assert_eq!(padded, plain);
}

/// The banner command has to work in the repository that reported the bug, whose
/// plan is not at the default root. It does because `roadmap` resolves `root:`
/// from `.aplan.yml`, and nothing asserted that: the fix would have been wrong
/// for exactly the adopter it was written for.
#[test]
fn the_bare_command_works_where_the_plan_is_not_at_the_default_root() {
    let dir = tempfile::Builder::new()
        .tempdir_in(aplan_core::fixture::fixture_root())
        .expect("tempdir");
    let root = dir.path();
    std::fs::create_dir_all(root.join("plans/tasks")).expect("plan dir");
    std::fs::write(root.join(".aplan.yml"), "root: plans\n").expect("config");
    std::fs::write(
        root.join("plans/tasks/M-v0.1.md"),
        "---\nid: M-v0.1\ntitle: The first cut of this fixture\nphase: 1\n\
         status: todo\nowner: kaminsod\ntags: [milestone]\nblocked_by: [A-1]\n---\n\n\
         ## Exit criteria\n\nSomething.\n",
    )
    .expect("milestone");
    std::fs::write(
        root.join("plans/tasks/A-1.md"),
        "---\nid: A-1\ntitle: A task that belongs to the first cut\nphase: 1\n\
         status: todo\nowner: kaminsod\neffort_days: 1\n---\n\n## Why\n\nSomething.\n",
    )
    .expect("task");

    // No `--root`: exactly the command the banner names, from the repository root.
    let (out, code) = aplan(root, &["roadmap", "--format", "markdown"]);
    assert_eq!(code, 0, "the banner's own command failed here:\n{out}");
    assert_eq!(regenerate_line(&out), "aplan roadmap --format markdown");
    assert!(
        out.contains("| A-1 |"),
        "it rendered someone else's plan:\n{out}"
    );
}

/// The criterion is "names the real output path, **or** names none rather than
/// the wrong one", and only the second branch was covered. The first is the
/// reporting pilot's actual case: their file is at `plans/ROADMAP.status.md`, and
/// they are the only ones who know that, so they must be able to say it.
#[test]
fn a_consumer_can_name_their_real_output_path() {
    let dir = repo();
    let named = "aplan roadmap --format markdown > plans/ROADMAP.status.md";
    let (out, code) = aplan(
        dir.path(),
        &[
            "roadmap",
            "--root",
            "aplan",
            "--format",
            "markdown",
            "--regenerate-with",
            named,
        ],
    );
    assert_eq!(code, 0, "{out}");
    assert_eq!(regenerate_line(&out), named, "{out}");
}
