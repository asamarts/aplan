//! The generated agent-contract block: its markers, and reading one out of a
//! file that carries it.
//!
//! `aplan export-agents-md` writes a fenced block into a repository's
//! `AGENTS.md`, and a repository keeps its own prose outside the markers. That
//! makes the block **a second copy of the policy**, which is the thing this tool
//! exists to distrust -- and the copy went stale in the field: `p00002`'s block
//! named `commit` as acceptable evidence for a day after `require_min_strength`
//! had dropped it, found by running `--check` on a hunch (`A1-273`).
//!
//! The markers live here rather than beside the renderer because three callers
//! read them -- the writer, the `--check` gate, and [`code::STALE_AGENT_CONTRACT`]
//! -- and a marker pair with two readers is how the block a tool owns and the
//! block it validates come to disagree.
//!
//! [`code::STALE_AGENT_CONTRACT`]: crate::code::STALE_AGENT_CONTRACT

/// The marker a generated block opens with, as this tool writes it.
pub const BEGIN: &str = "<!-- aplan:begin -- generated by `aplan export-agents-md`; edits between these markers are lost -->";

/// What every begin marker starts with.
///
/// **Writing the marker and recognising one are different questions.** The whole
/// of [`BEGIN`] is a hundred characters, and it has to be: it is where the next
/// reader of the file learns that their edits between the markers are lost. But
/// an adopter placing the block by hand in prose they already own writes
/// `<!-- aplan:begin -->`, which reads as a begin marker to any person, and was
/// counted as *zero* of them -- against a file that plainly had one, with no way
/// to see the difference short of reading this source (`A1-294`, from
/// pre-public adoption evidence).
///
/// So a marker is recognised by this prefix and rewritten to [`BEGIN`] whenever
/// the block is written, which keeps the file self-describing without asking
/// anybody to copy a hundred characters exactly.
pub const BEGIN_PREFIX: &str = "<!-- aplan:begin";

/// The marker a generated block closes with.
///
/// No prefix rule here, and the asymmetry is the measurement rather than an
/// oversight: this one is eighteen characters and the pilot that could not write
/// the opening marker wrote this one correctly.
pub const END: &str = "<!-- aplan:end -->";

/// Every begin marker in `text`, as byte ranges.
///
/// A marker is a *line* opening with [`BEGIN_PREFIX`], and it ends at its own
/// `-->` rather than at the end of the line: `BEGIN` followed by `END` on one
/// line is a block with nothing in it, and taking the line would swallow the
/// close. Line-anchored so prose about the marker is not one, and closed so a
/// sentence opening with the prefix is not either.
#[must_use]
pub fn begin_spans(text: &str) -> Vec<std::ops::Range<usize>> {
    const CLOSE: &str = "-->";
    let mut out = Vec::new();
    let mut at = 0usize;
    for line in text.split_inclusive('\n') {
        // Leading whitespace is indentation, not content: a marker inside a list
        // item is still the marker, and the old exact-substring match counted it.
        // The span starts at the marker rather than at the line, so rewriting it
        // keeps the indentation the author chose.
        let lead = line.len() - line.trim_start().len();
        let marker = &line[lead..];
        // **The prefix ends at a word boundary.** Without this,
        // `<!-- aplan:beginning of the notes -->` is a begin marker, and `--write`
        // replaces the adopter's own comment with the generated block: precisely
        // the "eat the prose" failure the refusals in this module exist to avoid,
        // introduced by the widening that was meant to help (`A1-294`, audit).
        // A space or a dash, which is every way the marker itself continues.
        if let Some(after) = marker.strip_prefix(BEGIN_PREFIX)
            && after.starts_with([' ', '-'])
            && let Some(i) = marker.find(CLOSE)
        {
            out.push(at + lead..at + lead + i + CLOSE.len());
        }
        at += line.len();
    }
    out
}

/// What a file has to say about a generated block.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Block<'a> {
    /// No markers at all. The repository never asked for a block, or removed the
    /// one it had, and nothing here is owed an opinion.
    Absent,
    /// A marker pair that cannot be read as one block: two of something, or an
    /// opening with no close.
    ///
    /// Reported rather than ignored, and that is the point of the variant: a
    /// rule that treated a half-block as "no block" could be silenced by
    /// deleting one comment line, which is the quietest possible way to turn a
    /// gate off (`A1-273`).
    Malformed {
        /// How many opening markers the file carries.
        begins: usize,
        /// How many closing markers it carries.
        ends: usize,
    },
    /// Exactly one block, with the text between the markers.
    Present(&'a str),
}

/// Read the generated block out of a document.
///
/// The text returned excludes both markers, so a caller comparing two blocks
/// compares what is generated rather than the fence around it.
#[must_use]
pub fn block_in(text: &str) -> Block<'_> {
    let spans = begin_spans(text);
    let begins = spans.len();
    let ends = text.matches(END).count();
    if begins == 0 && ends == 0 {
        return Block::Absent;
    }
    if begins != 1 || ends != 1 {
        return Block::Malformed { begins, ends };
    }
    let (Some(b), Some(e)) = (spans.first(), text.find(END)) else {
        return Block::Malformed { begins, ends };
    };
    // A close before its open is not a block, whatever the counts say: the text
    // "between" them runs backwards.
    if e < b.end {
        return Block::Malformed { begins, ends };
    }
    Block::Present(&text[b.end..e])
}

/// What the provenance line inside a generated block starts with (`A1-325`).
///
/// The rest of the line is the build's version and surface digest, which change;
/// this prefix does not, so a reader recognising the line does not have to parse
/// it. Kept here rather than beside the renderer because three places need it
/// and only one of them writes it: the renderer emits it, `APLAN041` asks
/// whether two blocks differ *only* in it, and `export-agents-md --check` says
/// which build is doing the checking.
pub const WRITTEN_BY_PREFIX: &str = "<!-- written by aplan ";

/// `text` with its provenance line removed, if it has one.
///
/// Used to ask what two blocks disagree about *apart from* which build wrote
/// them. Every line matching is dropped rather than only the first: a block that
/// somehow carried two is a block whose difference is still not about policy,
/// and reporting it as a policy change would be the wrong answer twice over.
#[must_use]
pub fn without_provenance(text: &str) -> String {
    text.lines()
        .filter(|l| !l.trim_start().starts_with(WRITTEN_BY_PREFIX))
        .collect::<Vec<_>>()
        .join("\n")
}

/// Whether two blocks say the same thing and were written by different builds.
///
/// The distinction `A1-325` exists to draw. A pinned binary in CI and a newer
/// one locally produce blocks that differ in one line, and calling that a policy
/// change sends the reader looking for a policy that did not change.
#[must_use]
pub fn differs_only_by_build(found: &str, want: &str) -> bool {
    found.trim() != want.trim()
        && without_provenance(found).trim() == without_provenance(want).trim()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn two_blocks_differing_only_in_who_wrote_them_say_so() {
        let one = format!("{WRITTEN_BY_PREFIX}0.2.0, surface aaaaaaaaaaaa -->\n- a rule\n");
        let two = format!("{WRITTEN_BY_PREFIX}0.4.0, surface bbbbbbbbbbbb -->\n- a rule\n");
        assert!(differs_only_by_build(&one, &two));
        assert_eq!(without_provenance(&one), without_provenance(&two));
    }

    #[test]
    fn a_real_difference_is_not_a_build_difference() {
        let one = format!("{WRITTEN_BY_PREFIX}0.2.0, surface aaaaaaaaaaaa -->\n- a rule\n");
        let two = format!("{WRITTEN_BY_PREFIX}0.4.0, surface bbbbbbbbbbbb -->\n- another\n");
        assert!(!differs_only_by_build(&one, &two));
    }

    #[test]
    fn identical_blocks_differ_in_nothing_at_all() {
        // Not a build difference either: the caller asks this question only
        // after establishing the two are not equal, and answering "yes" for
        // two equal blocks would make a matching file a finding.
        let one = format!("{WRITTEN_BY_PREFIX}0.4.0, surface bbbbbbbbbbbb -->\n- a rule\n");
        assert!(!differs_only_by_build(&one, &one.clone()));
    }

    #[test]
    fn a_block_with_no_provenance_line_is_left_alone() {
        // What a pre-`A1-325` build wrote. Against a block that has one, the
        // difference is still only the build.
        let old = "- a rule\n";
        let new = format!("{WRITTEN_BY_PREFIX}0.4.0, surface bbbbbbbbbbbb -->\n- a rule\n");
        assert_eq!(without_provenance(old), "- a rule");
        assert!(differs_only_by_build(old, &new));
    }

    #[test]
    fn an_indented_provenance_line_is_still_one() {
        // A block inside a list item carries the file's indentation, the same
        // way `an_indented_marker_keeps_its_indentation_and_still_counts`
        // covers for the marker.
        let text = format!("  {WRITTEN_BY_PREFIX}0.4.0, surface bbbbbbbbbbbb -->\n- a rule\n");
        assert_eq!(without_provenance(&text), "- a rule");
    }

    #[test]
    fn prose_mentioning_the_line_mid_sentence_is_not_stripped() {
        // Line-anchored, like the marker: a sentence *about* the provenance
        // line is the adopter's prose and removing it would make two blocks
        // look equal when they are not.
        let text = format!("the block opens with `{WRITTEN_BY_PREFIX}...`\n");
        assert_eq!(without_provenance(&text), text.trim_end());
    }

    #[test]
    fn a_plausible_begin_marker_is_one() {
        // The pilot's file. `<!-- aplan:begin -->` reads as a begin marker to any
        // person, and was counted as zero of them against a file that plainly had
        // one (`A1-294`).
        let text = "prose\n\n<!-- aplan:begin -->\nbody\n<!-- aplan:end -->\n\nprose\n";
        assert_eq!(block_in(text), Block::Present("\nbody\n"));
    }

    #[test]
    fn an_indented_marker_keeps_its_indentation_and_still_counts() {
        let text = format!("- a list item:\n\n    {BEGIN}\n  body\n    {END}\n");
        let spans = begin_spans(&text);
        assert_eq!(spans.len(), 1, "an indented marker stopped counting");
        assert_eq!(
            &text[spans[0].clone()],
            BEGIN,
            "the span took the indentation"
        );
    }

    /// `contract.begin_marker_matched_by_prefix` says *prefix*, and this is where
    /// the prefix stops.
    #[test]
    fn a_word_that_merely_starts_with_the_prefix_is_not_a_marker() {
        // The widening's own hazard: `beginning` opens with `begin`, and without
        // a boundary `--write` replaced the adopter's comment with the generated
        // block (`A1-294`, audit).
        for line in [
            "<!-- aplan:beginning of the notes -->\n",
            "<!-- aplan:begins here -->\n",
        ] {
            assert!(
                begin_spans(line).is_empty(),
                "counted a word as a marker: {line}"
            );
        }
        // And the three ways the marker itself continues all still count.
        for line in [
            "<!-- aplan:begin -->\n",
            "<!-- aplan:begin-->\n",
            "<!-- aplan:begin -- generated by something -->\n",
        ] {
            assert_eq!(
                begin_spans(line).len(),
                1,
                "stopped counting a marker: {line}"
            );
        }
    }

    /// The other half of `contract.begin_marker_matched_by_prefix`: the half that
    /// keeps a widened match from swallowing prose.
    #[test]
    fn a_marker_named_in_prose_is_not_a_marker() {
        // Line-anchored and closed, so a sentence *about* the marker is not one.
        for text in [
            "We write <!-- aplan:begin --> in that file.\n",
            "The marker opens `<!-- aplan:begin` and closes with an arrow.\n",
        ] {
            assert!(
                begin_spans(text).is_empty(),
                "counted prose as a marker: {text}"
            );
        }
    }

    fn wrap(body: &str) -> String {
        format!("prose above\n\n{BEGIN}\n{body}\n{END}\n\nprose below\n")
    }

    #[test]
    fn a_file_with_no_markers_carries_no_block() {
        assert_eq!(block_in("just prose\n"), Block::Absent);
    }

    #[test]
    fn the_text_between_the_markers_is_the_block_and_the_fence_is_not() {
        let text = wrap("## Policy\n\n- a rule");
        let Block::Present(found) = block_in(&text) else {
            panic!("not present: {text}")
        };
        assert_eq!(found.trim(), "## Policy\n\n- a rule");
        assert!(!found.contains("aplan:begin"), "kept the fence: {found:?}");
        assert!(!found.contains("prose above"), "reached outside: {found:?}");
    }

    /// Deleting one marker line is the quietest way to silence a gate, so a
    /// half-block is a finding rather than an absence (`A1-273`).
    #[test]
    fn half_a_block_is_malformed_and_not_absent() {
        let text = format!("prose\n\n{BEGIN}\nbody\n");
        assert_eq!(block_in(&text), Block::Malformed { begins: 1, ends: 0 });
        let text = format!("prose\n\nbody\n{END}\n");
        assert_eq!(block_in(&text), Block::Malformed { begins: 0, ends: 1 });
    }

    /// Two blocks is the case the writer refuses: one gets updated and the other
    /// goes on telling agents the old policy.
    #[test]
    fn two_blocks_are_malformed() {
        let text = format!("{}\n{}", wrap("first"), wrap("second"));
        assert_eq!(block_in(&text), Block::Malformed { begins: 2, ends: 2 });
    }

    #[test]
    fn a_close_before_its_open_is_not_a_block() {
        let text = format!("{END}\n\nbody\n\n{BEGIN}\n");
        assert_eq!(block_in(&text), Block::Malformed { begins: 1, ends: 1 });
    }

    /// The degenerate pair: markers adjacent, nothing between them. A repository
    /// that emptied its block still has one, and it is stale against any policy.
    #[test]
    fn an_empty_block_is_present_and_empty() {
        let text = format!("{BEGIN}{END}");
        assert_eq!(block_in(&text), Block::Present(""));
    }
}
