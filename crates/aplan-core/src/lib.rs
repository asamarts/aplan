//! `aplan-core`, the task model, loader, dependency graph, and validation
//! engine.
//!
//! # Why this exists
//!
//! A plan drifts from reality the moment someone writes `status: done` for
//! something nobody verified. No amount of tooling prevents a person from
//! lying; what tooling *can* do is refuse to accept a claim that carries no
//! proof, and refuse to accept a dependency graph that cannot be executed.
//!
//! `aplan` therefore enforces a small set of invariants (see
//! [`validate()`](crate::validate()):
//!
//! - `done` requires at least one piece of typed [`task::Evidence`];
//! - the `blocked_by` graph is acyclic and references only real tasks;
//! - a `done` task cannot depend on one that isn't;
//! - a `note` as evidence must carry a date;
//! - `traces` anchors must resolve to real headings in real documents.
//!
//! The last one is the interesting one: it links a task to the passage of a
//! document it is supposed to resolve, so closing the task obliges you to edit
//! the document.
//!
//! # Source of truth
//!
//! The Rust types are the spec. `schemas/v1/task.json` is *derived* from
//! [`task::Task`] via `schemars` and regenerated by `cargo xtask gen-schema`;
//! CI runs `--check` and fails on any diff. Prose is never a regenerable
//! source of truth.

/// Define an enum together with its complete `ALL` slice and `as_str`, from one
/// table, so the variant set, the enumerable registry, and the string names
/// cannot drift apart, the same discipline `define_rules!` gives `Rule`. This
/// is what stops `facts.json` from silently omitting a real variant: a variant
/// that is not in the table is not in the enum, so it is also not in `ALL`.
#[macro_export]
macro_rules! str_enum {
    (
        $(#[$emeta:meta])*
        $vis:vis enum $name:ident {
            $( $(#[$vmeta:meta])* $variant:ident = $str:literal ),+ $(,)?
        }
    ) => {
        $(#[$emeta])*
        $vis enum $name {
            $( $(#[$vmeta])* $variant ),+
        }

        impl $name {
            /// Every variant, in declaration order. Generated from the same table
            /// as the enum, so it can never omit one.
            $vis const ALL: &'static [$name] = &[ $( $name::$variant ),+ ];

            /// The canonical string name of this variant.
            $vis const fn as_str(self) -> &'static str {
                match self { $( $name::$variant => $str ),+ }
            }
        }
    };
}

