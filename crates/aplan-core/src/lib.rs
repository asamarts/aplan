#[cfg(test)]
mod dependency_sink {
    /// `aplan-core` is the workspace's dependency sink, it must not depend on
    /// any other `aplan-*` crate. HLD §7 and ROADMAP claim this is enforced by
    /// a test; this is that test.
    #[test]
    fn aplan_core_has_no_intra_workspace_deps() {
        for line in include_str!("../Cargo.toml").lines() {
            let key = line.trim();
            assert!(
                !key.starts_with("aplan-") && !key.starts_with("aplan_"),
                "aplan-core must not depend on `{key}`, it is the dependency sink"
            );
        }
    }
}
